#!/usr/bin/env node
// Separate, exact occurrence supplement: never regenerate the frozen tagger/corpus.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),read=p=>JSON.parse(fs.readFileSync(path.join(root,p))),hash=x=>crypto.createHash('sha256').update(JSON.stringify(x)).digest('hex'),clone=x=>JSON.parse(JSON.stringify(x));
const ledger=read('scripts/data/tikkun-qatan-occurrences-20261004.json'),sidecar=read('public/tikkun/column-marks.json'),pointing=read('public/tikkun/column-pointing.json');
if(ledger.schema!==1||ledger.records.length!==4)throw Error('Occurrence authority changed');
const packet={schema:1,authoritySha256:hash(ledger),books:{},column:{beforeHash:hash(sidecar),beforeRows:Object.keys(sidecar.rows).length,rows:{}}};
for(const slug of new Set(ledger.records.map(r=>r.slug))){
 const book=read('public/reader/medooyuk/'+slug+'.json'),after=clone(book),entries=[];
 for(const r of ledger.records.filter(r=>r.slug===slug)){
  const v=book.ch[r.chapter][r.verse],word=v.t[r.token],cs=word.match(/[א-ת][^א-ת]*/g),ref=`${slug}/${r.chapter}/${r.verse}`;
  if(r.letter!==0||word.replace(/[^א-ת]/g,'')!=='כל'||!cs[0].includes('\u05B8')||v.k[r.token]||v.m.some(m=>m[0]===r.token&&m[1]===r.letter&&m[2]==='qk'))throw Error('Occurrence drift/duplicate');
  const tuple=[r.token,r.letter,'qk',0];after.ch[r.chapter][r.verse].m.push(tuple);entries.push({chapter:r.chapter,verse:r.verse,tuple});
  const [column,loc,ti]=r.columnKey.split('/'),p=pointing.columns[column][loc][ti];
  if(p.length!==3||p[0]!=='כל'||pointing.refs[p[1]]!==ref||p[2].replace(/[^א-ת]/g,'')!=='כל'||sidecar.rows[r.columnKey])throw Error('Fixed-column association drift');
  packet.column.rows[r.columnKey]=[p[2],[[0,'qk']],ref];
 }
 packet.books[slug]={beforeHash:hash(book),afterHash:hash(after),entries};
}
const upgraded=clone(sidecar);Object.assign(upgraded.rows,packet.column.rows);upgraded.independentQatan={authoritySha256:packet.authoritySha256,occurrences:4};packet.column.afterHash=hash(upgraded);packet.column.afterRows=Object.keys(upgraded.rows).length;
const content=`/* Generated by scripts/build-tikkun-qatan-supplement.cjs.
 * Source corpus/pointing remain byte-exact. Four explicit qamats-only occurrences.
 * Whole input/final hashes reject source/metadata drift; no linguistic inference. */
(function(root){'use strict';
const packet=${JSON.stringify(packet)};
const copy=x=>JSON.parse(JSON.stringify(x));
function hash(x){return root.TikkunBoundaries.boundaryHash(x);}
function applyBook(book,expectedSlug){
 if(typeof expectedSlug!=='string'||!expectedSlug||!book||book.slug!==expectedSlug)throw Error('Qatan occurrence source mismatch: requested book identifier');
 const p=packet.books[expectedSlug];if(!p)return book;
 const h=hash(book);if(h===p.afterHash)return book;
 if(h!==p.beforeHash)throw Error('Qatan occurrence source mismatch');
 const result=copy(book);p.entries.forEach(e=>result.ch[e.chapter][e.verse].m.push(e.tuple.slice()));
 if(hash(result)!==p.afterHash)throw Error('Qatan occurrence output mismatch');return result;
}
function applyColumnMarks(marks){
 const p=packet.column,h=hash(marks);if(h===p.afterHash)return marks;
 if(h!==p.beforeHash)throw Error('Qatan column source mismatch');
 const result=copy(marks);Object.assign(result.rows,copy(p.rows));result.independentQatan={authoritySha256:packet.authoritySha256,occurrences:4};
 if(hash(result)!==p.afterHash)throw Error('Qatan column output mismatch');return result;
}
root.TikkunQatanOccurrences={applyBook,applyColumnMarks,afterRows:packet.column.afterRows,authoritySha256:packet.authoritySha256};
})(window);
`;
const target=path.join(root,'public/tikkun-qatan.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==content)throw Error('Generated qatan helper stale');console.log('Qatan supplement exact generation PASS');}
else {fs.writeFileSync(target,content);console.log(JSON.stringify({pass:true,occurrences:ledger.records.length,beforeRows:packet.column.beforeRows,afterRows:packet.column.afterRows,authoritySha256:packet.authoritySha256}));}
