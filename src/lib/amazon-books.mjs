export function amazonBookUrl(book) {
  return `https://www.amazon.com/dp/${book.asin}`;
}

export function booksForReaderPath(pathname) {
  if (typeof pathname !== 'string') return [];
  const match = /^\/reader\/([a-z0-9-]+)(?:\/([a-z0-9-]+)(?:\/([a-z0-9-]+))?)?\/?$/.exec(pathname);
  if (!match) return [];
  const [, book, part, section] = match;
  return amazonBooks.filter(entry => entry.readerRoutes.some(route =>
    route.book === book &&
    (!route.rootOnly || (!part && !section)) &&
    (!route.part || route.part === part) &&
    (!route.section || route.section === section)
  ));
}

export function readerBookCatalogLink(pathname) {
  if (/^\/reader\/?$/.test(pathname)) return { href: '/print-books/', label: 'Our books on Amazon' };
  const match = /^\/reader\/(likutay-halachos|likutay-nanach)(?:\/[a-z0-9-]+){0,2}\/?$/.exec(pathname);
  if (!match) return null;
  const title = match[1] === 'likutay-halachos' ? 'Likutay Halachos' : 'Likutay Nanach';
  return { href: `/print-books/#${match[1]}`, label: `${title} books on Amazon` };
}

// Explicit destinations are used only for nonnumeric Reader roots.
export function readerBookUrl(book) {
  if (book.readerUrl) return book.readerUrl;
  const route = book.readerRoutes[0];
  if (!route) return null;
  return `/reader/${route.book}/${route.part || '1'}/${route.section ? route.section + '/' : ''}`;
}
